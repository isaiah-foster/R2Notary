// Deploys r2notary with this deployment's names (DECISIONS D9.3). worker/wrangler.jsonc keeps
// placeholders; the real values are in worker/deploy.local.json (gitignored, format in
// scripts/lib/local-config.ts). This writes worker/wrangler.deploy.jsonc (gitignored, next to
// wrangler.jsonc so its relative paths still resolve) and runs `wrangler deploy` with it.
//
//   npm run deploy                 # deploy
//   npm run deploy -- --dry-run    # build and show the bindings, deploy nothing
//
// Further arguments go to `wrangler deploy`. Secrets are per Worker name, so
// `wrangler secret put <NAME> -c worker/wrangler.jsonc` still applies (docs/OPERATIONS.md §3).

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { validateOrigin } from '../packages/core/src/index.ts';
import { LOCAL_CONFIG, ROOT, readLocalConfig, replaceOnce } from './lib/local-config.ts';

const SOURCE = join(ROOT, 'worker/wrangler.jsonc');
const OUT = join(ROOT, 'worker/wrangler.deploy.jsonc');
/** Must be set: deploying a placeholder bucket or origin is never intended. */
const REQUIRED = ['MONITORED_BUCKET_NAME', 'LOG_BUCKET_NAME', 'LOG_ORIGIN'];
const BINDING_OF: Readonly<Record<string, string>> = {
  MONITORED_BUCKET_NAME: 'MONITORED',
  LOG_BUCKET_NAME: 'LOG',
};

const fail = (message: string): never => {
  console.error(`deploy: ${message}`);
  process.exit(2);
};
const escape = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const local = readLocalConfig() ?? fail(`no ${LOCAL_CONFIG} (see scripts/lib/local-config.ts)`);
const missing = REQUIRED.filter((k) => local.vars[k] === undefined);
if (missing.length > 0) fail(`worker/deploy.local.json: set vars ${missing.join(', ')}`);

let text = readFileSync(SOURCE, 'utf8');
const committed = (name: string): string =>
  new RegExp(`"${escape(name)}":\\s*"([^"]*)"`).exec(text)?.[1] ?? fail(`no var ${name}`);
const logName = local.vars.LOG_NAME ?? committed('LOG_NAME');

// What the Worker would refuse at startup, refused before deploying instead.
const origin = local.vars.LOG_ORIGIN ?? '';
try {
  validateOrigin(origin);
} catch (e) {
  fail(`LOG_ORIGIN: ${e instanceof Error ? e.message : String(e)}`);
}
if (!origin.endsWith(`/log/${logName}`)) {
  fail(`LOG_ORIGIN must end with /log/${logName}: the Worker serves the log there`);
}
if (local.vars.MONITORED_BUCKET_NAME === local.vars.LOG_BUCKET_NAME) {
  fail('MONITORED_BUCKET_NAME must differ from LOG_BUCKET_NAME');
}
const host = origin.split('/')[0] ?? '';
const patterns = (local.routes ?? []).map((r) => (typeof r.pattern === 'string' ? r.pattern : ''));
if (patterns.length > 0 && !patterns.some((p) => p === host || p.startsWith(`${host}/`))) {
  fail(`no route serves ${host}, the host LOG_ORIGIN names`);
}

for (const [name, value] of Object.entries(local.vars)) {
  text = replaceOnce(text, new RegExp(`("${escape(name)}":\\s*)"[^"]*"`), value, name);
  const binding = BINDING_OF[name];
  if (binding !== undefined) {
    text = replaceOnce(
      text,
      new RegExp(`("binding":\\s*"${binding}",\\s*"bucket_name":\\s*)"[^"]*"`),
      value,
      `the ${binding} bucket binding`,
    );
  }
}
// `wrangler deploy` refuses a required secret that is not set, and KEY_BLINDING_KEY is used only
// by a blinded log (D9.4). With blinding off it is not required, and need not be put.
const blinding = local.vars.KEY_BLINDING ?? committed('KEY_BLINDING');
if (blinding !== 'true') {
  const required = /,\s*"KEY_BLINDING_KEY"(\s*\])/;
  if (!required.test(text))
    fail('KEY_BLINDING_KEY is not in the required secrets of wrangler.jsonc');
  text = text.replace(required, '$1');
}
if (local.routes !== undefined) {
  text = text.replace('{', `{\n  "routes": ${JSON.stringify(local.routes)},`);
}
writeFileSync(
  OUT,
  `// Generated by scripts/deploy.ts from wrangler.jsonc and deploy.local.json. Do not edit or commit.\n${text}`,
);

const args = ['deploy', '-c', OUT, ...process.argv.slice(2)];
console.error(`deploy: wrangler ${args.join(' ')}`);
const r = spawnSync(join(ROOT, 'node_modules/.bin/wrangler'), args, {
  cwd: ROOT,
  stdio: 'inherit',
});
process.exit(r.status ?? 1);
